/// The library a file name names, as `OpenLibrary` is given it.
#[must_use]
pub fn library(name: &str) -> Option<&'static Library> {
    LIBRARIES.iter().find(|l| l.name == name)
}

impl Library {
    /// The function at `offset` from the base.
    #[must_use]
    pub fn function(&self, offset: i16) -> Option<&'static str> {
        self.functions
            .binary_search_by(|(o, _)| offset.cmp(o))
            .ok()
            .and_then(|i| self.functions.get(i))
            .map(|(_, n)| *n)
    }

    /// The library's short name: `dos`.
    #[must_use]
    pub fn short(&self) -> &'static str {
        self.name.strip_suffix(".library").unwrap_or(self.name)
    }
}
