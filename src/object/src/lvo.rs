//! Library vector offsets: which function a call through a library base
//! reaches (D-021).
//!
//! A program calls a library as `jsr -552(a6)` with the library's base in
//! `a6`; the offset picks the function, six bytes a slot counting back from
//! the base. Generated from AROS's library descriptions — each library's
//! `.conf` function list and, independently, the slot every function's own
//! source declares in its `AROS_LH` header. The two agree for all 895
//! functions here, and with offsets known from AmigaOS for 35 of them.
//! AROS-only additions — those it marks version 50 or later — are left out,
//! since an AmigaOS program of the period cannot call them; so are the slots
//! AROS marks private, whose names are AROS's, except five in exec that are
//! AmigaOS's own: `ExitIntr`, `Schedule`, `Switch`, `Dispatch` and
//! `StackSwap`.
//!
//! Generated from those sources, not written by hand; the sources stay
//! outside the repository, as AROS's other sources do.

